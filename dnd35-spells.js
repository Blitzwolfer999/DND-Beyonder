// Flat lookup by lowercased name -> { level per class }.
const D35_SPELL_INDEX = (function () {
  const index = {};
  Object.entries(D35_SPELL_LISTS).forEach(([cls, byLevel]) => {
    Object.entries(byLevel).forEach(([level, rows]) => {
      rows.forEach(row => {
        const key = row.name.toLowerCase();
        index[key] = index[key] || { name: row.name, desc: row.desc, classes: {} };
        index[key].classes[cls] = Number(level);
      });
    });
  });
  return index;
})();

